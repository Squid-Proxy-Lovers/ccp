"""Exercise attribution metadata without executing event text or trusting shallow history."""

import importlib.util
import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]


def load_checker():
    spec = importlib.util.spec_from_file_location(
        "attribution", ROOT / "scripts/check-attribution.py"
    )
    checker = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(checker)
    return checker


class AttributionTextTests(unittest.TestCase):
    def setUp(self):
        self.checker = load_checker()

    def test_human_coauthors_and_technical_mentions_are_allowed(self):
        message = (
            "fix(mcp): support Claude and Codex profiles\n\n"
            "Consult [Cursor documentation](https://cursor.com).\n\n"
            "Co-Authored-By: Claude Martin <claude.martin@example.com>\n"
            "Reviewed-by: Jane Developer <jane@example.com>\n"
        )
        self.assertEqual(self.checker.text_findings(message, commit=True), [])
        self.assertEqual(self.checker.text_findings("Providers:\nProvider: Codex"), [])
        self.assertEqual(
            self.checker.text_findings("![Cursor screenshot](https://example.com/a.png)"), []
        )

    def test_case_insensitive_and_folded_trailers(self):
        for trailer in (
            "cO-aUtHoReD-bY: cLaUdE <noreply@anthropic.com>",
            "Co-Authored-By:\n\tClaude Code <noreply@anthropic.com>",
            "Assisted-by: Claude\n Code",
            "Custom-Trailer: OpenAI Codex",
            "Signed-off-by: Cursor Agent <cursoragent@example.com>",
            "Custom-Trailer: OpenAI Codex\n\n",
            "Co-Authored-By: OpenAI Codex <other@example.com>",
            "Co-Authored-By: Claude Sonnet 4.5 <other@example.com>",
            "Co-Authored-By \t: Claude <noreply@anthropic.com>",
        ):
            with self.subTest(trailer=trailer):
                self.assertTrue(
                    self.checker.text_findings("fix: repair\n\n" + trailer, commit=True)
                )

    def test_generated_lines_and_linked_badges(self):
        for text in (
            "Generated with [Claude Code](https://claude.ai)",
            "**generated BY Codex**",
            "Written using GitHub Copilot",
            "[![Codex](https://img.shields.io/badge/Codex-blue)](https://openai.com)",
            "![Cursor](https://img.shields.io/badge/Cursor-blue)",
            "\U0001f916 [tool](https://example.com)",
        ):
            with self.subTest(text=text):
                self.assertTrue(self.checker.text_findings(text))
        self.assertEqual(self.checker.text_findings("Generated by the release build."), [])

    def test_exact_automation_exceptions_and_human_names(self):
        dependabot = self.checker.DEPENDABOT
        web = self.checker.WEB_FLOW
        self.assertFalse(self.checker.identity_problem(*dependabot, "author"))
        self.assertFalse(self.checker.identity_problem(*dependabot, "committer"))
        self.assertEqual(
            self.checker.text_findings(
                "chore(deps): refresh\n\nSigned-off-by: dependabot[bot] <support@github.com>\n",
                commit=True,
            ),
            [],
        )
        self.assertTrue(
            self.checker.identity_problem("dependabot[bot]", "support@github.com", "author")
        )
        self.assertFalse(self.checker.identity_problem(*web, "committer"))
        self.assertTrue(self.checker.identity_problem(*web, "author"))
        self.assertTrue(self.checker.identity_problem(dependabot[0], "fake@example.com", "author"))
        self.assertTrue(self.checker.identity_problem("other[bot]", dependabot[1], "author"))
        self.assertFalse(
            self.checker.identity_problem("Claude Martin", "claude@example.com", "author")
        )
        self.assertFalse(self.checker.identity_problem("Jane Human", "jane@openai.com", "author"))

    def test_tool_names_mailboxes_and_bot_aliases(self):
        for name, email in (
            ("Claude", "noreply@anthropic.com"),
            ("OpenAI", "author@example.com"),
            ("Codex", "author@example.com"),
            ("Copilot", "author@example.com"),
            ("Cursor Agent", "author@example.com"),
            ("T3 Code", "author@example.com"),
            ("Gemini", "author@example.com"),
            ("ChatGPT", "author@example.com"),
            ("Human-looking name", "123+copilot-swe-agent[bot]@users.noreply.github.com"),
            ("GitHub Actions", "github-actions[bot]@users.noreply.github.com"),
            ("GitHub Actions", "actions@github.com"),
            ("Ｃｏｄｅｘ", "author@example.com"),
        ):
            with self.subTest(name=name):
                self.assertTrue(self.checker.identity_problem(name, email, "author"))
                self.assertTrue(self.checker.identity_problem(name, email, "committer"))


class AttributionRepositoryTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.checker = load_checker()
        self.git_program = shutil.which("git")
        self.assertIsNotNone(self.git_program)
        self.git("init", "-q")
        self.git("config", "user.name", "Test Maintainer")
        self.git("config", "user.email", "maintainer@example.com")
        self.git("config", "core.hooksPath", "/dev/null")
        # Fixture commits must not inherit a developer's external signing service.
        self.git("config", "commit.gpgsign", "false")
        self.base = self.commit("chore: initialize")

    def git(self, *args, env=None):
        # Fixed executable; fixture arguments are separate and never evaluated by a shell.
        return (
            subprocess.run(  # noqa: S603 -- Isolated temporary Git repository.
                [self.git_program, *args], cwd=self.root, env=env, capture_output=True, check=True
            )
            .stdout.decode()
            .strip()
        )

    def commit(self, message, env=None):
        self.git("commit", "--allow-empty", "-q", "-m", message, env=env)
        return self.git("rev-parse", "HEAD")

    def event(self, data):
        path = self.root / "event.json"
        path.write_text(json.dumps(data))
        return path

    def pr(self, head, **fields):
        return {
            "base": {"sha": self.base},
            "head": {"sha": head},
            "title": "fix: repair",
            "body": None,
            **fields,
        }

    def test_every_commit_in_range_is_checked_and_full_history_includes_root(self):
        bad = self.commit("fix: repair\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
        head = self.commit("test: verify repair")
        selected = self.checker.commit_ids(self.root, f"{self.base}..{head}")
        self.assertEqual(set(selected), {bad, head})
        self.assertTrue(self.checker.commit_findings(self.root, bad))
        self.assertEqual(self.checker.commit_findings(self.root, head), [])
        self.assertEqual(set(self.checker.commit_ids(self.root, None)), {self.base, bad, head})

    def test_raw_author_and_committer_and_webflow_squash(self):
        env = {
            **os.environ,
            "GIT_AUTHOR_NAME": "Test Maintainer",
            "GIT_AUTHOR_EMAIL": "human@example.com",
            "GIT_COMMITTER_NAME": "GitHub",
            "GIT_COMMITTER_EMAIL": "noreply@github.com",
        }
        squash = self.commit("fix: squash human changes", env)
        self.assertEqual(self.checker.commit_findings(self.root, squash), [])
        for role in ("AUTHOR", "COMMITTER"):
            tool = {**env, f"GIT_{role}_NAME": "Codex", f"GIT_{role}_EMAIL": "codex@openai.com"}
            sha = self.commit("fix: repair", tool)
            self.assertIn(
                f"{role.lower()} uses a tool identity",
                "\n".join(self.checker.commit_findings(self.root, sha)),
            )
        (self.root / ".mailmap").write_text("Human <human@example.com> Codex <codex@openai.com>\n")
        self.assertTrue(self.checker.commit_findings(self.root, sha))

    def test_malicious_pr_metadata_remains_inert_json(self):
        head = self.commit("fix: repair")
        marker = self.root / "should-not-exist"
        body = f"$(touch {marker}) `touch {marker}`; echo bad\nProvider: Claude\n"
        event = self.event({"pull_request": self.pr(head, title="fix: $(exit 1)", body=body)})
        with patch.object(self.checker, "run", wraps=self.checker.run) as run:
            selection, problems = self.checker.event_selection(self.root, event)
        run.assert_not_called()
        self.assertEqual(selection, f"{self.base}..{head}")
        self.assertEqual(problems, [])
        self.assertFalse(marker.exists())
        for field in ("title", "body"):
            event = self.event({"pull_request": self.pr(head, **{field: "Generated by Codex"})})
            self.assertTrue(self.checker.event_selection(self.root, event)[1])

    def test_push_uses_before_after_and_rejects_missing_or_shallow_history(self):
        head = self.commit("fix: repair")
        event = self.event(
            {"ref": "refs/heads/main", "before": self.base, "after": head, "commits": []}
        )
        self.assertEqual(
            self.checker.event_selection(self.root, event), (f"{self.base}..{head}", [])
        )
        for invalid in (
            f"{'f' * 40}..HEAD",
            "HEAD...HEAD",
            "..HEAD",
            "--all..HEAD",
            "HEAD..$(exit 1)",
        ):
            with self.subTest(invalid=invalid), self.assertRaises(ValueError):
                self.checker.commit_ids(self.root, invalid)
        (self.root / ".git/shallow").write_text(self.base + "\n")
        with self.assertRaisesRegex(ValueError, "shallow history"):
            self.checker.commit_ids(self.root, None)
        event = self.event({"ref": "refs/heads/main", "before": "0" * 40, "after": head})
        with self.assertRaisesRegex(ValueError, "nonzero"):
            self.checker.event_selection(self.root, event)

    def test_dispatch_validates_number_and_fetches_actual_stacked_pr_endpoints(self):
        head = self.commit("fix: stacked change")
        pr = self.pr(head, number=42)
        with (
            patch.dict(os.environ, {"GITHUB_REPOSITORY": "owner/repo"}),
            patch.object(self.checker, "run", side_effect=[json.dumps(pr).encode(), b""]) as run,
        ):
            event = self.event({"inputs": {"pr_number": "42"}})
            self.assertEqual(
                self.checker.event_selection(self.root, event), (f"{self.base}..{head}", [])
            )
            self.assertEqual(
                run.call_args_list[0].args, (self.root, "gh", "api", "repos/owner/repo/pulls/42")
            )
            self.assertEqual(
                run.call_args_list[1].args,
                (self.root, "git", "fetch", "--no-tags", "origin", self.base, head),
            )
        for invalid in ("0", "-1", "42; touch marker", "$(exit 1)", "1/commits", 42):
            with (
                self.subTest(invalid=invalid),
                patch.object(self.checker, "run") as run,
                self.assertRaises(ValueError),
            ):
                self.checker.manual_pull_request(self.root, {"pr_number": invalid})
            run.assert_not_called()

    def test_malformed_event_and_failed_git_are_reported_as_failures(self):
        for data in ([], {"pull_request": {}}, {"ref": "refs/heads/other"}, {"inputs": {}}):
            with self.subTest(data=data), self.assertRaises(ValueError):
                self.checker.event_selection(self.root, self.event(data))
        with (
            patch.object(self.checker, "ROOT", self.root),
            patch("sys.argv", ["checker", "--range", "missing..HEAD"]),
            self.assertRaises(SystemExit) as failure,
        ):
            self.checker.main()
        self.assertEqual(failure.exception.code, 1)


if __name__ == "__main__":
    unittest.main()
